// Generates fixtures/default-basin-beta.json (blueprint §3): the default basin with β = 0.90 / 0.60 / 0.75 and r₀ = 1,
// no actions, no pumping, aquifer at B₀. Run after `npm run build`: `npm run fixtures:beta`. A change to this file's
// output is a parameter or equation change and follows CONTRIBUTING.md (say in the PR why the old values were wrong).

import { readFileSync, writeFileSync } from 'node:fs';
import { resolveSeason } from '../dist/index.js';

const here = (p) => new URL(p, import.meta.url);
const v1 = JSON.parse(readFileSync(here('../fixtures/default-basin-v1.json'), 'utf8'));
const scenario = JSON.parse(readFileSync(here('../../scenarios/default-basin.json'), 'utf8'));

const beta = scenario.schemes.map((s) => s.beta);
const schemes = v1.schemes.map((s, i) => ({ ...s, beta: beta[i] }));
const basin = { ...v1.basin, aquifer: { ...v1.basin.aquifer, naturalRecharge: scenario.basin.aquifer.naturalRecharge } };
const lenses = [
  ['utilitarian'], ['weighted_utilitarian'], ['egalitarian'], ['proportional'], ['capability'],
  ['sufficientarian'], ['prioritarian', { gamma: 3 }], ['equal_sacrifice'], ['talmud'],
];
const r2 = (x) => Math.round(x * 100) / 100 + 0; // + 0 turns −0 into 0

const out = {
  $comment: 'SPDX-License-Identifier: CC-BY-4.0 · Blueprint §3 β fixture set, generated by scripts/generate-beta-fixtures.mjs from the engine: β = 0.90 / 0.60 / 0.75, r₀ = 1, no actions, no pumping, B₀ = 20. Two decimals; Y to the tonne. Q, A, Y and the equity indicators equal the v1 set (β cancels in §2.4); F, S, r₃ and the aquifer differ.',
  generatedBy: 'packages/engine/scripts/generate-beta-fixtures.mjs',
  basin, scoring: v1.scoring, schemes,
};
for (const card of ['wet', 'normal', 'dry']) {
  out[card] = lenses.map(([lens, params]) => {
    const r = resolveSeason({ schemes, basin, inflow: basin.inflow[card], stock: basin.aquifer.initial, lens, lensParams: params, pumps: schemes.map(() => 0), scoring: v1.scoring });
    return {
      lens, ...(params ? { params } : {}),
      Q: r.allocation.Q.map(r2), A: r.A.map(r2), Y: r.Y.map(Math.round),
      ePJ: r2(r.ePJ), eSE: r2(r.eSE.claimant), F: { consumed: r2(r.F.consumed), diverted: r2(r.F.diverted) }, S: r2(r.S), r3: r2(r.triangle.r3),
      returnFlow: r2(r.returnFlow), stockNext: r2(r.stockNext),
      welfare: { UWF: r2(r.welfare.UWF), PWF3: r2(r.welfare.PWF), EWF: r2(r.welfare.EWF), CWF: r2(r.welfare.CWF), SWF: r2(r.welfare.SWF) },
    };
  });
}

const rows = (card) => out[card].map((row) => '    ' + JSON.stringify(row).replace(/,"/g, ', "').replace(/":/g, '": ')).join(',\n');
const head = JSON.stringify({ $comment: out.$comment, generatedBy: out.generatedBy, basin, scoring: out.scoring, schemes }, null, 2).slice(0, -2);
writeFileSync(here('../fixtures/default-basin-beta.json'), `${head},\n  "wet": [\n${rows('wet')}\n  ],\n  "normal": [\n${rows('normal')}\n  ],\n  "dry": [\n${rows('dry')}\n  ]\n}\n`);
console.log('wrote fixtures/default-basin-beta.json');
